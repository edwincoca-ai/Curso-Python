# Operadores aritmeticos.
print(2 + 2) # Suma
print(4 - 2) # Resta
print(3 * 7) # Multiplicacion
print(15 / 2) # Division
print(11 % 4) # Modulo
print(11 // 4) # Divicion de piso
print(2 ** 3) # Potenciacion

# Operadores en cadena
print("hola" + "mundo") # Concatenacion
print("hola" * 3) # Repeticion
print("hola" + "mundo" * 3)

# Operadores de comparacion
print("hola" == "hola") # Igual que 
print("hola" != "hola") # Distinto que
print(3 > 11) # Mayor que 
print(3 < 11) # Menor que
print(11 >= 10) #Mayor igual que
print(11 <= 10) #Menor igual que

# Operadores de existencia
print("ola" in "hola") # De existencia 
print("ola" not in "hola") # De inixistencia

# Operadores Booleanos
print(True or False) # or verifica que se cumpla una de las condiciones.
print(True and False) # and verifica que se cumplan las 2 condiciones

# Operadores de asignacion
x = 1 # operador de asignacion estandar 
x += 2 # operador de asignacion suma
x *= 3 # operador de asignacion multiplicacion
x %= 4 # operador de asignacion modulo
print(x)

x = 6 * 5 + 8 / 2 ** 4
